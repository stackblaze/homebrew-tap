#!/usr/bin/env bash
# Regenerate Formula/stackblaze.rb from the public GHCR OCI artifact.
#
#   scripts/update-formula.sh <tag>      e.g. v1.0.0, latest, dev, v1.0.0-dev.66
#
# The StackBlaze CLI repo is private, so its GitHub Release assets are not
# publicly downloadable. Binaries are published anonymously to
# ghcr.io/stackblaze/stackblaze-cli (one layer per platform, filename in the
# layer annotation org.opencontainers.image.title, version in the manifest
# annotation org.opencontainers.image.version). This script resolves the
# manifest for <tag>, picks the per-platform layer digests and writes a
# formula whose URLs point straight at the immutable blob digests.
#
# Requires: bash, curl, python3.
set -euo pipefail

TAG="${1:-}"
[ -n "$TAG" ] || { echo "usage: $0 <tag>" >&2; exit 2; }

REGISTRY="ghcr.io"
REPOSITORY="${STACKBLAZE_GHCR_REPOSITORY:-stackblaze/stackblaze-cli}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${ROOT}/Formula/stackblaze.rb"

token="$(curl -fsSL "https://${REGISTRY}/token?scope=repository:${REPOSITORY}:pull" |
  python3 -c 'import json,sys; print(json.load(sys.stdin)["token"])')"

manifest="$(curl -fsSL \
  -H "Authorization: Bearer ${token}" \
  -H "Accept: application/vnd.oci.image.manifest.v1+json" \
  "https://${REGISTRY}/v2/${REPOSITORY}/manifests/${TAG}")"

# Emits: VERSION=<v> and <platform>=<sha256 hex> lines.
parsed="$(printf '%s' "$manifest" | python3 -c '
import json, re, sys
m = json.load(sys.stdin)
version = (m.get("annotations") or {}).get("org.opencontainers.image.version", "")
if not version:
    sys.exit("manifest has no org.opencontainers.image.version annotation")
print("VERSION=" + version.lstrip("v"))
want = ["darwin-arm64", "darwin-x64", "linux-arm64", "linux-x64"]
found = {}
for layer in m.get("layers", []):
    title = (layer.get("annotations") or {}).get("org.opencontainers.image.title", "")
    for p in want:
        if title.endswith("-" + p):
            d = layer["digest"]
            if not re.fullmatch(r"sha256:[0-9a-f]{64}", d):
                sys.exit("unexpected digest " + d)
            found[p] = d.split(":", 1)[1]
missing = [p for p in want if p not in found]
if missing:
    sys.exit("manifest is missing platforms: " + ", ".join(missing))
for p in want:
    print(p.replace("-", "_") + "=" + found[p])
')"

eval "$parsed"  # VERSION, darwin_arm64, darwin_x64, linux_arm64, linux_x64

blob() { printf 'https://%s/v2/%s/blobs/sha256:%s' "$REGISTRY" "$REPOSITORY" "$1"; }

note=""
case "$VERSION" in
  *-*) note="
  # NOTE: built from a PRERELEASE (${TAG} -> ${VERSION}) so the tap can be
  # tested before the first stable release. The first stable release of the
  # CLI dispatches cli-release to this repo and overwrites this file.
" ;;
esac

cat >"$OUT" <<EOF
# typed: false
# frozen_string_literal: true

# GENERATED by scripts/update-formula.sh ${TAG} -- do not edit by hand.
#
# Binaries come from the public GHCR OCI artifact
# ghcr.io/${REPOSITORY} (one blob per platform, addressed by digest).
class Stackblaze < Formula
  desc "Command-line interface for the StackBlaze cloud platform"
  homepage "https://www.stackblaze.com/docs/reference/cli"
  version "${VERSION}"
  license "MIT"
${note}
  on_macos do
    on_arm do
      url "$(blob "$darwin_arm64")",
          using: CurlGitHubPackagesDownloadStrategy
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "$(blob "$darwin_x64")",
          using: CurlGitHubPackagesDownloadStrategy
      sha256 "${darwin_x64}"
    end
  end

  on_linux do
    on_arm do
      url "$(blob "$linux_arm64")",
          using: CurlGitHubPackagesDownloadStrategy
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "$(blob "$linux_x64")",
          using: CurlGitHubPackagesDownloadStrategy
      sha256 "${linux_x64}"
    end
  end

  def install
    # The blob is the raw executable; Homebrew stages it under whatever
    # basename the download resolved to, so take the single staged file.
    files = Dir["*"].select { |f| File.file?(f) }
    odie "expected exactly one staged file, got: #{files.inspect}" if files.length != 1
    bin.install files.first => "stackblaze"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/stackblaze --version")
  end
end
EOF

echo "wrote ${OUT} (version ${VERSION} from ${TAG})"
